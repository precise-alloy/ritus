// Bundles src/main.ts and every dependency into ../dist/jev.js (the only runtime artifact) and writes the
// licenses of bundled packages to ../dist/THIRD_PARTY_NOTICES.txt. `--check` fails when the committed files are stale.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const here = import.meta.dir;
const dist = resolve(here, "..", "dist");
const bundlePath = join(dist, "jev.js");
const noticesPath = join(dist, "THIRD_PARTY_NOTICES.txt");
const checkOnly = process.argv.includes("--check");

const result = await Bun.build({
  entrypoints: [join(here, "src", "main.ts")],
  target: "bun",
  format: "esm",
  minify: true,
  sourcemap: "none",
  metafile: true,
  banner: "// ritus-jev MCP server bundle - generated by ritus-jev/server/build.ts; edit ritus-jev/server/src and rebuild.",
});
if (!result.success || result.outputs.length !== 1) {
  for (const log of result.logs) console.error(log);
  throw new Error("Bundle failed");
}
const bundle = (await (result.outputs[0] as Blob).text()).replace(/\r\n/g, "\n");

const packageRoots = new Set<string>();
for (const input of Object.keys(result.metafile?.inputs ?? {})) {
  const parts = resolve(process.cwd(), input).split(/[\\/]/);
  const index = parts.lastIndexOf("node_modules");
  if (index < 0 || !parts[index + 1]) continue;
  const depth = (parts[index + 1] as string).startsWith("@") ? 3 : 2;
  packageRoots.add(parts.slice(0, index + depth).join("/"));
}

const packages = new Map<string, { version: string; license: string; texts: string[] }>();
for (const root of packageRoots) {
  const meta = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as { name: string; version: string; license?: string };
  const files = (await readdir(root)).filter((file) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(file)).sort();
  const texts = await Promise.all(files.map(async (file) => (await readFile(join(root, file), "utf8")).replace(/\r\n/g, "\n").trim()));
  packages.set(`${meta.name}@${meta.version}`, { version: meta.version, license: meta.license ?? "UNKNOWN", texts });
}
const notices = [
  "Third-party software bundled into dist/jev.js",
  "",
  ...[...packages.entries()].sort(([a], [b]) => a.localeCompare(b)).flatMap(([name, entry]) => [
    "=".repeat(78),
    `${name} (${entry.license})`,
    "=".repeat(78),
    ...(entry.texts.length > 0 ? entry.texts : ["License text not shipped with the package; see its package.json."]),
    "",
  ]),
].join("\n");

if (checkOnly) {
  const [current, currentNotices] = await Promise.all([
    readFile(bundlePath, "utf8").catch(() => ""),
    readFile(noticesPath, "utf8").catch(() => ""),
  ]);
  if (current !== bundle || currentNotices !== notices) {
    console.error("dist/ is stale: run `bun run build` in ritus-jev/server and commit the result.");
    process.exit(1);
  }
  console.log(`dist/ is current (${bundle.length} bytes, ${packages.size} bundled packages).`);
} else {
  await mkdir(dist, { recursive: true });
  await writeFile(bundlePath, bundle);
  await writeFile(noticesPath, notices);
  console.log(`Wrote dist/jev.js (${bundle.length} bytes) and THIRD_PARTY_NOTICES.txt (${packages.size} packages).`);
}
